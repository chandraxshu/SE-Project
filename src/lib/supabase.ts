import { createClient } from '@supabase/supabase-js';

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL || 'https://placeholder.supabase.co';
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY || 'placeholder-anon-key';

if (!import.meta.env.VITE_SUPABASE_URL || !import.meta.env.VITE_SUPABASE_ANON_KEY) {
  console.warn(
    '[Khoj IIITA] Supabase environment variables missing. Falling back to placeholder client. Please configure VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY in your .env file.'
  );
}

export const supabase = createClient(supabaseUrl, supabaseAnonKey, {
  auth: {
    autoRefreshToken: true,
    persistSession: true,
    detectSessionInUrl: true,
  },
});

// Allowed email domain
export const ALLOWED_EMAIL_DOMAIN = 'iiita.ac.in';

export function isAllowedEmail(email: string): boolean {
  if (!email || typeof email !== 'string') return false;
  return email.endsWith(`@${ALLOWED_EMAIL_DOMAIN}`);
}
